#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
from pathlib import Path


RANGE_RE = re.compile(
    r"\(\s*'\\u\{(?P<lo>[0-9a-f]+)\}'\s*,\s*"
    r"'\\u\{(?P<hi>[0-9a-f]+)\}'\s*,\s*"
    r"(?P<class>[A-Z]+)\s*\)",
    re.MULTILINE,
)
PAIR_RE = re.compile(
    r"\(\s*'\\u\{(?P<opening>[0-9a-f]+)\}'\s*,\s*"
    r"'\\u\{(?P<closing>[0-9a-f]+)\}'\s*,\s*"
    r"(?P<skeleton>None|Some\('\\u\{[0-9a-f]+\}'\))\s*\)",
    re.MULTILINE,
)
SKELETON_RE = re.compile(r"Some\('\\u\{(?P<skeleton>[0-9a-f]+)\}'\)")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate C# BidiClass tables from unicode-bidi tables.rs.")
    parser.add_argument("--tables-rs", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()

    source = args.tables_rs.read_text(encoding="utf-8")
    ranges = [
        (int(match.group("lo"), 16), int(match.group("hi"), 16), match.group("class"))
        for match in RANGE_RE.finditer(source)
    ]
    pairs = []
    for match in PAIR_RE.finditer(source):
        skeleton = match.group("skeleton")
        skeleton_match = SKELETON_RE.fullmatch(skeleton)
        pairs.append((
            int(match.group("opening"), 16),
            int(match.group("closing"), 16),
            int(skeleton_match.group("skeleton"), 16) if skeleton_match else None,
        ))

    if not ranges:
        raise RuntimeError(f"No bidi class ranges found in {args.tables_rs}")
    if not pairs:
        raise RuntimeError(f"No bidi bracket pairs found in {args.tables_rs}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(ranges, pairs), encoding="utf-8")
    return 0


def render(ranges: list[tuple[int, int, str]], pairs: list[tuple[int, int, int | None]]) -> str:
    rows = "\n".join(
        f"        new(0x{lo:X}, 0x{hi:X}, BidiClass.{bidi_class}),"
        for lo, hi, bidi_class in ranges
    )
    pair_rows = "\n".join(
        f"        new(0x{opening:X}, 0x{closing:X}, {f'0x{skeleton:X}' if skeleton is not None else 'null'}),"
        for opening, closing, skeleton in pairs
    )

    return f"""// <auto-generated />
/*
 * Copyright (c) 2006 Erik A. Brandstadmoen (C#/.NET port modifications/adaptations).
 * Generated from Rust unicode-bidi source with AI assistance.
 *
 * UNICODE_BIDI_RUST_SOURCE_PATH: src/char_data/tables.rs
 * UNICODE_BIDI_RUST_VERSION: 0.3.18
 * PORT_MODE: generated
 */

/*
 * Copyright 2015 The Servo Project Developers. See THIRD-PARTY-NOTICES.md.
 *
 * Licensed under the Apache License, Version 2.0 or the MIT license, at your option.
 */

namespace Unicode.Bidi.char_data;

internal static class Tables
{{
    internal static readonly BidiClassRange[] BidiClassTable =
    [
{rows}
    ];

    internal static readonly BidiPair[] BidiPairTable =
    [
{pair_rows}
    ];
}}
"""


if __name__ == "__main__":
    raise SystemExit(main())
